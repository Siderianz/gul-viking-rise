function applyLanguage(lang) {
  const dictionary = translations[lang] || translations.ru;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  if (lang === "en") {
    translatePlainText(textTranslations.en);
  }

  document.querySelectorAll("input[data-placeholder-i18n]").forEach((input) => {
    const key = input.dataset.placeholderI18n;
    if (dictionary[key]) {
      input.placeholder = dictionary[key];
    }
  });

  localStorage.setItem("guildLanguage", lang);
  window.dispatchEvent(new CustomEvent("guild-language-change", { detail: { lang } }));
}

function translatePlainText(dictionary) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];

  while (walker.nextNode()) {
    nodes.push(walker.currentNode);
  }

  nodes.forEach((node) => {
    const key = node.textContent.trim();
    if (key && dictionary[key]) {
      node.textContent = node.textContent.replace(key, dictionary[key]);
    }
  });
}

function initLanguageGate() {
  const gate = document.querySelector("[data-language-gate]");
  const savedLanguage = localStorage.getItem("guildLanguage");

  if (gate) {
    document.body.classList.add("has-language-gate");
    document.querySelectorAll("[data-lang-choice]").forEach((button) => {
      button.addEventListener("click", () => {
        applyLanguage(button.dataset.langChoice);
        gate.classList.add("is-hidden");
        document.body.classList.remove("has-language-gate");
      });
    });
    return;
  }

  applyLanguage(savedLanguage || "ru");
}

initLanguageGate();
